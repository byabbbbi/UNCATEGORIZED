import type { Concept, PillarKey } from '../types'

/** 조합 키는 이름 정렬 (`a+b`) — generation.pairKey와 동일 */
export type HardEntry = Omit<Concept, 'id' | 'depth' | 'deleted'> & {
  depth?: number
  chronicle: string
}

export type HardTable = Record<string, HardEntry>

function pairKey(a: string, b: string): string {
  return [a, b].sort().join('+')
}

function hard(
  name: string,
  emoji: string,
  chaos: number,
  plausibility: number,
  narrative: number,
  contagion: number,
  pillar: PillarKey,
  chronicle: string,
  depth = 1,
): HardEntry {
  return {
    name,
    emoji,
    chaos,
    plausibility,
    narrative,
    contagion,
    pillar,
    chronicle,
    depth,
  }
}

/** 새 엔트리용: chaos 20~45, plausibility 45~75 */
function n(
  a: string,
  b: string,
  name: string,
  emoji: string,
  pillar: PillarKey,
  chronicle: string,
  depth: number,
  chaos = 28,
  plaus = 58,
  narr = 32,
  cont = 22,
): [string, HardEntry] {
  return [
    pairKey(a, b),
    hard(name, emoji, chaos, plaus, narr, cont, pillar, chronicle, depth),
  ]
}

